func TestGroupLoadsChildrenRecursively(t *testing.T) {
	ctx := core.NewRoot("root")
	t.Cleanup(ctx.Dispose)
	log := []string{}
	instance := mustProvide(t, ctx, map[string]loader.PluginFactory{
		"a": recorder(&log, "a"),
		"b": recorder(&log, "b"),
	})

	if _, err := instance.Load(loader.LoaderEntry{
		ID:    "g",
		Group: true,
		Children: []loader.LoaderEntry{
			{ID: "g:a", Name: "a"},
			{ID: "g:b", Name: "b"},
		},
	}); err != nil {
		t.Fatalf("加载分组失败：%v", err)
	}

	if ids := instance.IDs(); !reflect.DeepEqual(ids, []string{"g", "g:a", "g:b"}) {
		t.Fatalf("已加载 = %v，期望 [g g:a g:b]", ids)
	}
	if !reflect.DeepEqual(log, []string{"a", "b"}) {
		t.Fatalf("加载日志 = %v，期望 [a b]", log)
	}
}

func TestRemoveCascadesToDescendantsInReverseOrder(t *testing.T) {
	ctx := core.NewRoot("root")
	t.Cleanup(ctx.Dispose)
	log := []string{}
	instance := mustProvide(t, ctx, map[string]loader.PluginFactory{
		"a": recorder(&log, "a"),
		"b": recorder(&log, "b"),
	})

	if _, err := instance.Load(loader.LoaderEntry{
		ID:    "g",
		Group: true,
		Children: []loader.LoaderEntry{
			{ID: "g:a", Name: "a"},
			{ID: "g:b", Name: "b"},
		},
	}); err != nil {
		t.Fatalf("加载分组失败：%v", err)
	}

	if err := instance.Remove("g"); err != nil {
		t.Fatalf("卸载分组失败：%v", err)
	}

	if len(instance.IDs()) != 0 {
		t.Fatalf("级联卸载后应为空：%v", instance.IDs())
	}
	if want := []string{"a", "b", "b:off", "a:off"}; !reflect.DeepEqual(log, want) {
		t.Fatalf("卸载顺序 = %v，期望 %v（后代先于祖先，LIFO）", log, want)
	}
}

func TestReloadRestartsPlugin(t *testing.T) {
	ctx := core.NewRoot("root")
	t.Cleanup(ctx.Dispose)
	log := []string{}
	instance := mustProvide(t, ctx, map[string]loader.PluginFactory{"a": recorder(&log, "a")})

	if _, err := instance.Load(loader.LoaderEntry{ID: "a1", Name: "a"}); err != nil {
		t.Fatalf("加载失败：%v", err)
	}
	if err := instance.Reload("a1"); err != nil {
		t.Fatalf("重启失败：%v", err)
	}

	if want := []string{"a", "a:off", "a"}; !reflect.DeepEqual(log, want) {
		t.Fatalf("重启日志 = %v，期望 %v", log, want)
	}
	if _, found := instance.ContextOf("a1"); !found {
		t.Fatal("重启后应有新的子上下文")
	}
	if err := instance.Reload("absent"); !errors.Is(err, loader.ErrUnknownEntry) {
		t.Fatalf("重启未知 entry = %v，期望 ErrUnknownEntry", err)
	}
}

func TestApplyReplacesWholeTree(t *testing.T) {
	ctx := core.NewRoot("root")
	t.Cleanup(ctx.Dispose)
	log := []string{}
	instance := mustProvide(t, ctx, map[string]loader.PluginFactory{"a": recorder(&log, "a")})

	if _, err := instance.Load(loader.LoaderEntry{ID: "old", Name: "a"}); err != nil {
		t.Fatalf("加载失败：%v", err)
	}
	if err := instance.Apply([]loader.LoaderEntry{{ID: "new", Name: "a"}}); err != nil {
		t.Fatalf("全量替换失败：%v", err)
	}

	if want := []string{"a", "a:off", "a"}; !reflect.DeepEqual(log, want) {
		t.Fatalf("替换日志 = %v，期望 %v", log, want)
	}
	if ids := instance.IDs(); !reflect.DeepEqual(ids, []string{"new"}) {
		t.Fatalf("替换后已加载 = %v，期望 [new]", ids)
	}
	if _, found := instance.ContextOf("old"); found {
		t.Fatal("替换后旧 entry 不该还在")
	}
}

func TestAutoGeneratedIDsAndChildPrefix(t *testing.T) {
	ctx := core.NewRoot("root")
	t.Cleanup(ctx.Dispose)
	instance := mustProvide(t, ctx, map[string]loader.PluginFactory{"a": noopFactory})

	groupID, err := instance.Load(loader.LoaderEntry{
		Group:    true,
		Children: []loader.LoaderEntry{{Name: "a"}},
	})
	if err != nil {
		t.Fatalf("加载失败：%v", err)
	}
	if _, err := instance.Load(loader.LoaderEntry{Name: "a"}); err != nil {
		t.Fatalf("加载失败：%v", err)
	}

	if !strings.HasPrefix(groupID, "entry-") {
		t.Fatalf("自动 id = %q，期望 entry-*", groupID)
	}
	prefixed := 0
	for _, id := range instance.IDs() {
		if strings.HasPrefix(id, groupID+":") {
			prefixed++
		}
	}
	if prefixed != 1 {
		t.Fatalf("带父前缀的子节点数 = %d，期望 1（已加载 %v）", prefixed, instance.IDs())
	}
}

func TestEntryJSONRoundTripAndApplyJSON(t *testing.T) {
	entry := loader.LoaderEntry{
		ID:    "g",
		Group: true,
		Children: []loader.LoaderEntry{
			{ID: "g:a", Name: "a", Config: "v", Disabled: true},
		},
	}

	restored, err := loader.EntryFromJSON(entry.JSON())
	if err != nil {
		t.Fatalf("还原失败：%v", err)
	}
	if restored.ID != "g" || !restored.Group || len(restored.Children) != 1 {
		t.Fatalf("还原结果 = %+v", restored)
	}
	child := restored.Children[0]
	if child.Name != "a" || !child.Disabled || child.Config != "v" {
		t.Fatalf("子节点 = %+v", child)
	}

	ctx := core.NewRoot("root")
	t.Cleanup(ctx.Dispose)
	log := []string{}
	instance := mustProvide(t, ctx, map[string]loader.PluginFactory{
		"a": func(_ *core.Context, config any) error {
			log = append(log, fmt.Sprint(config))
			return nil
		},
	})
	if err := instance.ApplyJSON([]map[string]any{{"id": "live", "name": "a", "config": "x"}}); err != nil {
		t.Fatalf("applyJson 失败：%v", err)
	}
	if !reflect.DeepEqual(log, []string{"x"}) {
		t.Fatalf("配置未透传：%v", log)
	}
}

